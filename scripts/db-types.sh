#!/usr/bin/env bash
# Regenerates src/lib/supabase/database.types.ts from supabase/migrations without
# Docker: applies the migrations to a throwaway database on a plain Postgres
# server, generates the types from it, and drops the database again.
#
# SCRATCH_DB_URL points at that server (any database on it; default below), as
# a user that may create databases and roles. No Postgres at hand? Push the
# branch: CI runs this script and shows the expected file when it differs.
set -euo pipefail

server_url="${SCRATCH_DB_URL:-postgresql://postgres:postgres@127.0.0.1:5432/postgres}"
scratch_db="types_scratch_$$"
scratch_url="${server_url%/*}/${scratch_db}"
out="src/lib/supabase/database.types.ts"
export PGOPTIONS="-c client_min_messages=error"

psql "$server_url" -qX -c "create database ${scratch_db}"
trap 'psql "$server_url" -qX -c "drop database if exists ${scratch_db}"' EXIT

psql "$scratch_url" -qX -v ON_ERROR_STOP=1 -f supabase/scratch/supabase-stub.sql
supabase db push --remote="$scratch_url" --yes >/dev/null
{
  echo "// Generated by \`npm run db:types\` from supabase/migrations. Do not edit by hand."
  # The CompositeTypes helper unions in \`never\` while the schema has no composite types.
  echo "/* oxlint-disable typescript/no-redundant-type-constituents -- generated helper, see scripts/db-types.sh */"
  supabase gen types typescript --schema public --remote="$scratch_url" 2>/dev/null
} >"$out"
oxfmt "$out"
echo "Wrote $out"
